export type I18nKey = keyof (typeof messages)['zh']

export function t(locale: Locale, key: I18nKey, vars?: Record<string, string | number>): string {
  const table = messages[locale] ?? messages.zh
  let raw: string = table[key] ?? messages.zh[key]
  if (!vars) return raw
  for (const [name, value] of Object.entries(vars)) {
    raw = raw.split(`{${name}}`).join(String(value))
  }
  return raw
}
